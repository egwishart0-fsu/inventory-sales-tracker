# This program stores product information and calculates the subtotal based of the price and product quantity.

# Product information
product_name = "Mug"
product_price = 6.50
product_quantity = 4

# Calculate the subtotal
subtotal = product_price * product_quantity

# Display product information
print("Product:", product_name)
print(f"Price per unit: $ {product_price:.2f}")
print("Quantity:", product_quantity)
print(f"Subtotal: $ {subtotal:.2f}")
